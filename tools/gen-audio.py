#!/usr/bin/env python3
# Pre-generate English speech clips for the treasure hunt (world/treasure.js)
# and the quiz gate (world/quiz.js), so the site never depends on a live TTS
# service at runtime (the player is in China; Google/Baidu may be slow there).
#
# Every fixed English text the site speaks is collected from:
#   - world/hunt-steps.js   clue lines (hand-authored)
#   - world/hunt-data.js    every word/phrase and every sentence (generated)
#   - EXTRA_TEXTS below     quiz UI strings + the hunt completion line
# Clips are downloaded ONCE, here, from Google Translate TTS; if a clip fails
# there it falls back to Baidu fanyi gettts (and is reported). Output:
#   assets/audio/<slug>.mp3  and  world/audio-manifest.js (text -> path)
#
# Usage: python3 tools/gen-audio.py
import hashlib
import json
import re
import sys
import time
import urllib.parse
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT_DIR = ROOT / "assets" / "audio"
MANIFEST = ROOT / "world" / "audio-manifest.js"
UA = ("Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 "
      "(KHTML, like Gecko) Chrome/120.0 Safari/537.36")

# Fixed strings spoken by world/quiz.js and world/treasure.js that do not come
# from the hunt data. Keep in sync with the code.
EXTRA_TEXTS = [
    "Question time!",
    "What does this word mean?",
    "Well done!",
    "Try again!",
    "Well done! You found all the treasures!",
]


def collect_texts():
    texts, seen = [], set()

    def add(t):
        t = (t or "").strip()
        if t and t not in seen:
            seen.add(t)
            texts.append(t)

    steps = (ROOT / "world" / "hunt-steps.js").read_text(encoding="utf-8")
    for m in re.finditer(r"""clue:\s*"((?:[^"\\]|\\.)*)"|clue:\s*'((?:[^'\\]|\\.)*)'""", steps):
        add(m.group(1) or m.group(2))

    raw = (ROOT / "world" / "hunt-data.js").read_text(encoding="utf-8")
    data = json.loads(raw[raw.index("{"):raw.rindex("}") + 1])
    for unit in data.values():
        for w in unit.get("words", []):
            add(w.get("word"))
        for s in unit.get("sentences", []):
            add(s.get("english"))

    for t in EXTRA_TEXTS:
        add(t)
    return texts


def slugify(text, taken):
    slug = re.sub(r"[^a-z0-9]+", "-", text.lower()).strip("-")[:48].strip("-") or "clip"
    if slug in taken and taken[slug] != text:
        slug = f"{slug}-{hashlib.md5(text.encode()).hexdigest()[:6]}"
    taken[slug] = text
    return slug


def fetch(url):
    req = urllib.request.Request(url, headers={"User-Agent": UA, "Referer": "https://translate.google.com/"})
    with urllib.request.urlopen(req, timeout=25) as r:
        data = r.read()
    if len(data) < 800 or not (data[:3] == b"ID3" or data[0] == 0xFF):
        raise ValueError(f"not an mp3 ({len(data)} bytes)")
    return data


def download(text):
    """Return (bytes, source) trying Google TTS, then Baidu gettts."""
    enc = urllib.parse.quote(text)
    google = f"https://translate.google.com/translate_tts?ie=UTF-8&client=tw-ob&tl=en&q={enc}"
    baidu = f"https://fanyi.baidu.com/gettts?lan=en&text={enc}&spd=3&source=web"
    last_err = None
    for attempt in range(2):
        try:
            return fetch(google), "google"
        except Exception as e:  # noqa: BLE001 - report and fall back below
            last_err = e
            time.sleep(0.6)
    try:
        return fetch(baidu), "baidu"
    except Exception as e:  # noqa: BLE001
        raise RuntimeError(f"google: {last_err}; baidu: {e}") from e


def main():
    texts = collect_texts()
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    taken, manifest, failures = {}, {}, []
    baidu_used, total_bytes = [], 0
    for i, text in enumerate(texts, 1):
        slug = slugify(text, taken)
        path = OUT_DIR / f"{slug}.mp3"
        try:
            data, source = download(text)
        except Exception as e:  # noqa: BLE001
            failures.append((text, str(e)))
            print(f"[{i}/{len(texts)}] FAILED {text!r}: {e}")
            continue
        path.write_bytes(data)
        total_bytes += len(data)
        if source == "baidu":
            baidu_used.append(text)
        manifest[text] = f"assets/audio/{slug}.mp3"
        print(f"[{i}/{len(texts)}] {source:6s} {len(data):6d}B  {text!r} -> {slug}.mp3")
        time.sleep(0.15)

    body = json.dumps(manifest, ensure_ascii=False, indent=2, sort_keys=True)
    MANIFEST.write_text(
        "// GENERATED by tools/gen-audio.py - do not edit by hand.\n"
        "// Maps exact English text to its pre-generated speech clip.\n"
        f"export const AUDIO_CLIPS = {body};\n",
        encoding="utf-8",
    )
    print(f"\n{len(manifest)}/{len(texts)} clips, {total_bytes} bytes total "
          f"({total_bytes / 1048576:.2f} MiB), manifest: {MANIFEST.relative_to(ROOT)}")
    if baidu_used:
        print(f"Google failed, Baidu fallback used for {len(baidu_used)}: {baidu_used}")
    if failures:
        print(f"FAILURES ({len(failures)}): {[t for t, _ in failures]}")
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
