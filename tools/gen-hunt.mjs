// Generate world/hunt-data.js for the English treasure hunt (U1–U5)
// from the daughter-english-app data files — the single source of truth.
// Usage: node tools/gen-hunt.mjs [path-to-daughter-english-app]
//   (or set DAUGHTER_APP_DIR; default: /tmp/daughter-english-app, then ../daughter-english-app)
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const repo = fileURLToPath(new URL('../', import.meta.url));
const candidates = [
  process.argv[2],
  process.env.DAUGHTER_APP_DIR,
  '/tmp/daughter-english-app',
  resolve(repo, '../daughter-english-app'),
].filter(Boolean);
const appDir = candidates.find(d => existsSync(join(d, 'src/data/vocabulary.json')));
if (!appDir) {
  console.error(`gen-hunt: could not find daughter-english-app (looked in: ${candidates.join(', ')})`);
  console.error('Clone https://github.com/guiren88/daughter-english-app first, or pass its path as an argument.');
  process.exit(1);
}

const UNITS = ['Unit 1', 'Unit 2', 'Unit 3', 'Unit 4', 'Unit 5']; // all of 2A Units 1–5; add a unit here to generate more
const vocab = JSON.parse(readFileSync(join(appDir, 'src/data/vocabulary.json'), 'utf8'));
const stories = JSON.parse(readFileSync(join(appDir, 'src/data/stories.json'), 'utf8'));
const grade = vocab.grade_2a;
if (!grade) { console.error('gen-hunt: vocabulary.json has no grade_2a'); process.exit(1); }
const gradeStories = stories.grade_2a || [];

const out = {};
for (const unitName of UNITS) {
  const u = grade.find(x => x.unit === unitName);
  if (!u) { console.error(`gen-hunt: ${unitName} not found in grade_2a`); process.exit(1); }
  const story = gradeStories.find(s => s.unit === unitName) || null;
  const key = 'u' + unitName.split(' ')[1];
  out[key] = {
    id: key,
    unit: u.unit,
    title: u.title,
    words: u.words,
    sentences: u.sentences,
    tips: u.tips || [],
    story: story && {
      title: story.title,
      titleCn: story.titleCn,
      coverEmoji: story.coverEmoji,
      summary: story.summary,
      coreWords: story.coreWords,
    },
  };
  console.log(`gen-hunt: ${unitName} 《${u.title}》 — ${u.words.length} words, ${u.sentences.length} sentences, story coreWords: ${story ? story.coreWords.length : 0}`);
}

const banner = `// GENERATED by tools/gen-hunt.mjs from daughter-english-app
// (src/data/vocabulary.json + src/data/stories.json, grade_2a).
// Do NOT edit by hand — regenerate with: node tools/gen-hunt.mjs [path-to-daughter-english-app]
// Hand-authored hunt steps live in world/hunt-steps.js; they reference this
// data by word and sentence index, so word/sentence content is never copied twice.
`;
writeFileSync(join(repo, 'world/hunt-data.js'), banner + '\nexport const HUNT_UNITS = ' + JSON.stringify(out, null, 2) + ';\n');
console.log(`gen-hunt: wrote world/hunt-data.js from ${appDir}`);
